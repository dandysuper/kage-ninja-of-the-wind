--  CONTROLS
--    Left/Right .......... run
--    Down ................ crouch / slide
--    Z (or A) ............ jump  (hold for higher, tap again = double jump)
--    X (or S) ............ katana slash  (air slash while airborne)
--    Up + X .............. throw kunai
--    Down + Z (in air) ... air dash (once per airtime)
--    Up (at shrine) ...... rest / save / fast travel
--
